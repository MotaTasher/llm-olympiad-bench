def main() -> int:
    parser = argparse.ArgumentParser(description="Add review-required drafts for missing final comments.")
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--competitions-dir", type=Path, default=Path("data/competitions"))
    parser.add_argument("--logs-dir", type=Path, default=Path("logs"))
    parser.add_argument("--results-dir", type=Path, default=Path("data/results"))
    args = parser.parse_args()

    catalog = build_catalog(
        competitions_dir=args.competitions_dir,
        logs_dir=args.logs_dir,
        results_dir=args.results_dir,
    )
    eligible = []
    pending = []
    for competition_id in ("math-cup-2026-qualifying", "math-cup-2026-final"):
        competition = catalog["competition_map"][competition_id]
        for row in finalization_statistics(competition)["tasks"]:
            problem = row["problem"]
            for cell in row["cells"].values():
                attempt = cell["attempt"]
                final = attempt.get("finalization") if attempt else None
                if not final or float(final["score"]) >= float(problem["max_score"]):
                    continue
                eligible.append(attempt["result_id"])
                if str(final.get("feedback") or "").strip():
                    continue
                pending.append((competition_id, problem, attempt, final))

    missing_drafts = [attempt["result_id"] for _, _, attempt, _ in pending if attempt["result_id"] not in DRAFTS]
    if missing_drafts:
        raise SystemExit(f"Missing editorial drafts for: {', '.join(missing_drafts)}")
    unused = sorted(set(DRAFTS) - set(eligible))
    if unused:
        raise SystemExit(f"Draft table contains stale result IDs: {', '.join(unused)}")

    print(f"Would add {len(pending)} review-required final-comment drafts.")
    if not args.apply:
        return 0
    for competition_id, problem, attempt, final in pending:
        save_finalization(
            results_dir=args.results_dir,
            competition_id=competition_id,
            problem_id=problem["problem_id"],
            run_id=attempt["run_id"],
            result_id=attempt["result_id"],
            result_index=int(attempt["result_index"]),
            model_key_value=attempt["model_key"],
            model=attempt["model_id"],
            score=final["score"],
            max_score=float(problem["max_score"]),
            feedback=DRAFTS[attempt["result_id"]],
            updated_by="gpt-draft",
            feedback_review_required=True,
        )
    print(f"Added {len(pending)} drafts; every draft requires human review.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
